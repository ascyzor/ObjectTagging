# Evaluation arguments for the DEVA + LangSeg pipeline.
# These replace the SAM-specific arguments from ext_eval_args.py.
# This file is intentionally kept separate so neither pipeline modifies the other.
from argparse import ArgumentParser


def add_ext_eval_args_lseg(parser: ArgumentParser):
    """Register LangSeg-specific arguments."""

    # Path to the pre-computed per-frame instance mask PNGs produced by
    # lseg_inference.py (feature-3dgs venv, Python 3.10).
    # Expected format: 16-bit grayscale PNG, pixel value = instance ID (0 = background).
    parser.add_argument(
        '--lseg_mask_dir',
        required=True,
        help='Directory containing per-frame instance mask PNGs generated by lseg_inference.py.',
    )

    # Path to the id2label_lseg.json written by lseg_inference.py.
    # Format: {"1": "chair", "2": "table", ...}
    parser.add_argument(
        '--id2label_lseg',
        required=True,
        help='Path to id2label_lseg.json produced by lseg_inference.py.',
    )


def add_lseg_default_args(parser: ArgumentParser):
    """Runtime defaults for the DEVA loop in the LangSeg pipeline."""

    parser.add_argument('--img_path', default='./example/vipseg')

    # Every frame is used as a detection frame because LangSeg already provides
    # a fresh semantic segmentation per frame (no points-per-side budget like SAM).
    parser.add_argument(
        '--detection_every',
        type=int,
        default=1,
        help='How often (in frames) to feed a new LangSeg mask into DEVA. '
             'Default 1 = every frame.',
    )

    parser.add_argument(
        '--num_voting_frames',
        default=3,
        type=int,
        help='Number of frames used for semionline voting. Only valid in semionline mode.',
    )

    parser.add_argument('--temporal_setting', default='semionline',
                        help='semionline / online')

    parser.add_argument('--max_missed_detection_count', type=int, default=5)

    parser.add_argument(
        '--max_num_objects',
        default=200,
        type=int,
        help='Max number of objects kept in DEVA memory. -1 for no limit.',
    )

    return parser